import React, { useState } from 'react';
import { Q2Q3AnalysisResult } from '../types';
import { formatCurrency, formatPercent } from '../utils/analytics';
import {
  Brain,
  Check,
  CheckCircle2,
  Copy,
  Download,
  ExternalLink,
  Flame,
  HelpCircle,
  RefreshCw,
  ShieldCheck,
  Sparkles,
  TrendingUp,
} from 'lucide-react';

interface AiSummaryCardProps {
  analysis: Q2Q3AnalysisResult;
  summaryText: string;
  isLoading: boolean;
  onRefresh: () => void;
  sourceType: string;
}

export const AiSummaryCard: React.FC<AiSummaryCardProps> = ({
  analysis,
  summaryText,
  isLoading,
  onRefresh,
  sourceType,
}) => {
  const [copied, setCopied] = useState(false);
  const [showLedger, setShowLedger] = useState(false);

  const { mostChangedByAbsolute, hasQ2AndQ3 } = analysis;

  const handleCopy = () => {
    if (!summaryText) return;
    navigator.clipboard.writeText(summaryText);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownloadSummary = () => {
    if (!summaryText || !mostChangedByAbsolute) return;

    const reportContent = `========================================================================
EXECUTIVE SALES INTELLIGENCE REPORT: Q2 TO Q3 REGIONAL VARIANCE
Generated by: SalesOrder Analytics (${sourceType === 'gemini-3.8-flash' ? 'Gemini 3.8 Flash' : 'Calculation Engine'})
Timestamp: ${new Date().toLocaleString()}
========================================================================

AI THREE-SENTENCE EXECUTIVE SUMMARY:
------------------------------------------------------------------------
${summaryText}

AUDITED METRICS CALCULATED BY THE APPLICATION:
------------------------------------------------------------------------
• Most Changed Region: ${mostChangedByAbsolute.region}
• Q2 Total Revenue: ${formatCurrency(mostChangedByAbsolute.q2Revenue)}
• Q3 Total Revenue: ${formatCurrency(mostChangedByAbsolute.q3Revenue)}
• Net Revenue Shift: ${mostChangedByAbsolute.diffRevenue >= 0 ? '+' : ''}${formatCurrency(mostChangedByAbsolute.diffRevenue)} (${formatPercent(mostChangedByAbsolute.pctChange)})
• Order Units Shift: ${mostChangedByAbsolute.q2Units.toLocaleString()} units -> ${mostChangedByAbsolute.q3Units.toLocaleString()} units (Net: ${mostChangedByAbsolute.diffUnits >= 0 ? '+' : ''}${mostChangedByAbsolute.diffUnits.toLocaleString()})
• Average Discount Rate: ${mostChangedByAbsolute.q2AvgDiscountPct.toFixed(1)}% -> ${mostChangedByAbsolute.q3AvgDiscountPct.toFixed(1)}%
${
  mostChangedByAbsolute.topProductByDiff
    ? `• Top Product Driver: "${mostChangedByAbsolute.topProductByDiff.product}" (Q2: ${formatCurrency(
        mostChangedByAbsolute.topProductByDiff.q2Revenue
      )}, Q3: ${formatCurrency(mostChangedByAbsolute.topProductByDiff.q3Revenue)}, Shift: ${formatCurrency(
        mostChangedByAbsolute.topProductByDiff.diffRevenue
      )})`
    : ''
}
${
  mostChangedByAbsolute.topChannelByDiff
    ? `• Top Channel Driver: "${mostChangedByAbsolute.topChannelByDiff.channel}" (Q2: ${formatCurrency(
        mostChangedByAbsolute.topChannelByDiff.q2Revenue
      )}, Q3: ${formatCurrency(mostChangedByAbsolute.topChannelByDiff.q3Revenue)}, Shift: ${formatCurrency(
        mostChangedByAbsolute.topChannelByDiff.diffRevenue
      )})`
    : ''
}

ALL REGIONAL Q2 -> Q3 SHIFTS:
------------------------------------------------------------------------
${analysis.regionsAnalyzed
  .map(
    (r, i) =>
      `${i + 1}. ${r.region}: ${formatCurrency(r.q2Revenue)} -> ${formatCurrency(r.q3Revenue)} | Delta: ${
        r.diffRevenue >= 0 ? '+' : ''
      }${formatCurrency(r.diffRevenue)} (${formatPercent(r.pctChange)})`
  )
  .join('\n')}

========================================================================
Verification Guarantee: All numbers cited strictly derived from order CSV.
========================================================================
`;

    const blob = new Blob([reportContent], { type: 'text/plain;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.setAttribute('download', `sales_summary_q2_q3_${mostChangedByAbsolute.region.toLowerCase().replace(/\s+/g, '_')}.txt`);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
  };

  if (!hasQ2AndQ3) {
    return (
      <div className="bg-amber-50 dark:bg-amber-950/30 border border-amber-200 dark:border-amber-800 rounded-xl p-5">
        <div className="flex items-start gap-3">
          <HelpCircle className="w-5 h-5 text-amber-600 dark:text-amber-400 mt-0.5 flex-shrink-0" />
          <div>
            <h4 className="text-sm font-semibold text-amber-900 dark:text-amber-200">
              Q2 and Q3 Data Required for AI Variance Summary
            </h4>
            <p className="text-xs text-amber-700 dark:text-amber-400 mt-1">
              The AI summary analyzes which region shifted the most between the second quarter (Q2) and
              third quarter (Q3). Please upload a sales order CSV that includes orders labeled with Q2 and Q3.
            </p>
          </div>
        </div>
      </div>
    );
  }

  // Split summary into sentences for enhanced readability
  const sentences = summaryText
    ? summaryText
        .split(/(?<=[.!?])\s+/)
        .filter((s) => s.trim().length > 0)
    : [];

  return (
    <div className="relative overflow-hidden bg-gradient-to-br from-indigo-900 via-slate-900 to-slate-950 text-white rounded-2xl p-6 shadow-xl border border-indigo-500/20">
      {/* Decorative background glow */}
      <div className="absolute -top-24 -right-24 w-80 h-80 bg-indigo-500/15 rounded-full blur-3xl pointer-events-none" />
      <div className="absolute -bottom-24 -left-24 w-80 h-80 bg-blue-500/15 rounded-full blur-3xl pointer-events-none" />

      {/* Card Header */}
      <div className="relative z-10 flex flex-col sm:flex-row sm:items-center justify-between gap-4 pb-4 border-b border-indigo-500/20">
        <div className="flex items-center gap-3">
          <div className="p-2.5 rounded-xl bg-indigo-500/20 text-indigo-300 ring-1 ring-indigo-400/30 backdrop-blur-sm">
            <Sparkles className="w-6 h-6 animate-pulse" />
          </div>
          <div>
            <div className="flex items-center gap-2">
              <h3 className="text-lg font-bold text-white tracking-tight">
                AI Q2 → Q3 Regional Variance Summary
              </h3>
              <span className="inline-flex items-center gap-1 px-2.5 py-0.5 rounded-full text-[11px] font-medium bg-indigo-400/10 text-indigo-300 border border-indigo-400/30">
                <Brain className="w-3 h-3" />
                {sourceType === 'gemini-3.8-flash' ? 'Gemini 3.8 Flash' : 'App Calculated Engine'}
              </span>
            </div>
            <p className="text-xs text-indigo-200/70 mt-0.5">
              Three-sentence executive brief driven strictly by app-computed figures
            </p>
          </div>
        </div>

        {/* Action Controls */}
        <div className="flex items-center gap-2">
          <button
            type="button"
            onClick={onRefresh}
            disabled={isLoading}
            className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-semibold bg-white/10 hover:bg-white/15 text-indigo-100 hover:text-white transition-all disabled:opacity-50 border border-white/10"
            title="Re-run AI summary generation"
          >
            <RefreshCw className={`w-3.5 h-3.5 ${isLoading ? 'animate-spin' : ''}`} />
            <span>{isLoading ? 'Analyzing...' : 'Refresh'}</span>
          </button>

          <button
            type="button"
            onClick={handleCopy}
            className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-semibold bg-indigo-600 hover:bg-indigo-500 text-white transition-all shadow-md shadow-indigo-600/30"
          >
            {copied ? (
              <>
                <Check className="w-3.5 h-3.5 text-emerald-300" />
                <span>Copied!</span>
              </>
            ) : (
              <>
                <Copy className="w-3.5 h-3.5" />
                <span>Copy</span>
              </>
            )}
          </button>

          <button
            type="button"
            onClick={handleDownloadSummary}
            className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-semibold bg-white/10 hover:bg-white/20 text-white transition-all border border-white/20 shadow-xs"
            title="Download full 3-sentence summary and audited figures as text report"
          >
            <Download className="w-3.5 h-3.5 text-indigo-300" />
            <span>Download Summary</span>
          </button>
        </div>
      </div>

      {/* Main Content Area */}
      <div className="relative z-10 py-5">
        {isLoading ? (
          <div className="py-8 flex flex-col items-center justify-center space-y-3">
            <div className="w-8 h-8 border-2 border-indigo-400 border-t-transparent rounded-full animate-spin" />
            <p className="text-sm text-indigo-200">
              Synthesizing calculated regional deltas with Gemini 3.8 Flash...
            </p>
          </div>
        ) : (
          <div className="space-y-4">
            {/* The 3-Sentence Breakdown */}
            <div className="space-y-3">
              {sentences.length === 3 ? (
                sentences.map((sentence, idx) => {
                  const labels = [
                    { title: 'Sentence 1: Region & Revenue Delta', color: 'border-l-indigo-400 bg-indigo-500/10' },
                    { title: 'Sentence 2: Primary Product Driver', color: 'border-l-emerald-400 bg-emerald-500/10' },
                    { title: 'Sentence 3: Channel & Volume Factor', color: 'border-l-amber-400 bg-amber-500/10' },
                  ];
                  const label = labels[idx] || labels[0];
                  return (
                    <div
                      key={`sentence-${idx}`}
                      className={`p-3.5 rounded-lg border-l-4 ${label.color} backdrop-blur-sm transition-all`}
                    >
                      <div className="text-[11px] uppercase tracking-wider font-semibold text-indigo-300/80 mb-1">
                        {label.title}
                      </div>
                      <p className="text-sm md:text-base text-slate-100 font-normal leading-relaxed">
                        {sentence}
                      </p>
                    </div>
                  );
                })
              ) : (
                <div className="p-4 rounded-xl bg-white/5 border border-white/10">
                  <p className="text-base text-slate-100 leading-relaxed font-normal">
                    {summaryText}
                  </p>
                </div>
              )}
            </div>

            {/* Quick Metrics Bar of the Leading Region */}
            {mostChangedByAbsolute && (
              <div className="mt-4 grid grid-cols-2 sm:grid-cols-4 gap-3 p-3 rounded-xl bg-black/30 border border-white/10 text-xs">
                <div>
                  <div className="text-slate-400 text-[11px]">Region Changed Most</div>
                  <div className="text-sm font-bold text-white mt-0.5 flex items-center gap-1">
                    <span>{mostChangedByAbsolute.region}</span>
                    <Flame className="w-3.5 h-3.5 text-amber-400 fill-amber-400" />
                  </div>
                </div>
                <div>
                  <div className="text-slate-400 text-[11px]">Q2 → Q3 Shift ($)</div>
                  <div
                    className={`text-sm font-mono font-bold mt-0.5 ${
                      mostChangedByAbsolute.diffRevenue >= 0 ? 'text-emerald-400' : 'text-rose-400'
                    }`}
                  >
                    {mostChangedByAbsolute.diffRevenue >= 0 ? '+' : ''}
                    {formatCurrency(mostChangedByAbsolute.diffRevenue)}
                  </div>
                </div>
                <div>
                  <div className="text-slate-400 text-[11px]">Percentage Growth</div>
                  <div className="text-sm font-mono font-bold text-indigo-300 mt-0.5">
                    {formatPercent(mostChangedByAbsolute.pctChange)}
                  </div>
                </div>
                <div>
                  <div className="text-slate-400 text-[11px]">Top Product Contributor</div>
                  <div className="text-sm font-medium text-slate-200 mt-0.5 truncate" title={mostChangedByAbsolute.topProductByDiff?.product}>
                    {mostChangedByAbsolute.topProductByDiff?.product || 'N/A'}
                  </div>
                </div>
              </div>
            )}
          </div>
        )}
      </div>

      {/* Audit & Calculations Ledger Toggle */}
      <div className="relative z-10 pt-3 border-t border-indigo-500/20 flex items-center justify-between">
        <button
          type="button"
          onClick={() => setShowLedger(!showLedger)}
          className="inline-flex items-center gap-1.5 text-xs text-indigo-300 hover:text-white transition-colors"
        >
          <ShieldCheck className="w-4 h-4 text-emerald-400" />
          <span className="font-medium">
            {showLedger ? 'Hide Audited Calculated Numbers' : 'View Numbers Calculated by App (Fed to AI)'}
          </span>
        </button>

        <span className="text-[11px] text-slate-400 flex items-center gap-1">
          <CheckCircle2 className="w-3.5 h-3.5 text-emerald-400" />
          Strict 100% data fidelity guarantee
        </span>
      </div>

      {/* Expandable Verification Ledger */}
      {showLedger && mostChangedByAbsolute && (
        <div className="relative z-10 mt-4 p-4 rounded-xl bg-slate-950/80 border border-indigo-500/30 text-xs space-y-3">
          <div className="flex items-center justify-between pb-2 border-b border-white/10">
            <span className="font-semibold text-indigo-200">
              Calculation Ledger for {mostChangedByAbsolute.region}
            </span>
            <span className="text-[10px] text-slate-400 uppercase tracking-wider font-mono">
              Deterministic Output
            </span>
          </div>

          <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
            <div className="space-y-1.5">
              <div className="flex justify-between py-1 border-b border-white/5">
                <span className="text-slate-400">Q2 Total Revenue:</span>
                <span className="font-mono text-white font-semibold">
                  {formatCurrency(mostChangedByAbsolute.q2Revenue)}
                </span>
              </div>
              <div className="flex justify-between py-1 border-b border-white/5">
                <span className="text-slate-400">Q3 Total Revenue:</span>
                <span className="font-mono text-white font-semibold">
                  {formatCurrency(mostChangedByAbsolute.q3Revenue)}
                </span>
              </div>
              <div className="flex justify-between py-1 border-b border-white/5">
                <span className="text-slate-400">Calculated Dollar Delta:</span>
                <span className="font-mono text-emerald-400 font-bold">
                  {formatCurrency(mostChangedByAbsolute.diffRevenue)}
                </span>
              </div>
              <div className="flex justify-between py-1">
                <span className="text-slate-400">Calculated % Change:</span>
                <span className="font-mono text-indigo-300 font-bold">
                  {formatPercent(mostChangedByAbsolute.pctChange)}
                </span>
              </div>
            </div>

            <div className="space-y-1.5">
              <div className="flex justify-between py-1 border-b border-white/5">
                <span className="text-slate-400">Order Units (Q2 → Q3):</span>
                <span className="font-mono text-white">
                  {mostChangedByAbsolute.q2Units.toLocaleString()} → {mostChangedByAbsolute.q3Units.toLocaleString()} (
                  {mostChangedByAbsolute.diffUnits >= 0 ? '+' : ''}
                  {mostChangedByAbsolute.diffUnits})
                </span>
              </div>
              <div className="flex justify-between py-1 border-b border-white/5">
                <span className="text-slate-400">Avg Discount Rate:</span>
                <span className="font-mono text-white">
                  {mostChangedByAbsolute.q2AvgDiscountPct.toFixed(1)}% → {mostChangedByAbsolute.q3AvgDiscountPct.toFixed(1)}%
                </span>
              </div>
              {mostChangedByAbsolute.topProductByDiff && (
                <div className="flex justify-between py-1 border-b border-white/5">
                  <span className="text-slate-400">Top Product Impact:</span>
                  <span className="font-mono text-slate-200">
                    {mostChangedByAbsolute.topProductByDiff.product} ({formatCurrency(mostChangedByAbsolute.topProductByDiff.diffRevenue)})
                  </span>
                </div>
              )}
              {mostChangedByAbsolute.topChannelByDiff && (
                <div className="flex justify-between py-1">
                  <span className="text-slate-400">Top Channel Impact:</span>
                  <span className="font-mono text-slate-200">
                    {mostChangedByAbsolute.topChannelByDiff.channel} ({formatCurrency(mostChangedByAbsolute.topChannelByDiff.diffRevenue)})
                  </span>
                </div>
              )}
            </div>
          </div>
        </div>
      )}
    </div>
  );
};
